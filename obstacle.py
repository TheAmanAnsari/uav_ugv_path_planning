def calculate_vertices(obstacle_coord):
    obstacles_coord_vertices = list()
    for cuboid in obstacle_coord:
        x, y, z = cuboid['center']
        l, b, w = cuboid['size']
        obstacles_coord_vertices.append(
            [
                (x + l/2, y + b/2, z + w/2), # V1
                (x + l/2, y + b/2, z - w/2), # V2
                (x + l/2, y - b/2, z + w/2), # V3
                (x + l/2, y - b/2, z - w/2), # V4
                (x - l/2, y + b/2, z + w/2), # V5
                (x - l/2, y + b/2, z - w/2), # V6
                (x - l/2, y - b/2, z + w/2), # V7
                (x - l/2, y - b/2, z - w/2)  # V8
            ]
        )
    return obstacles_coord_vertices

def top_or_base(vertices_list):
    base_and_top_vertices = []
    for vertices in vertices_list:
        base, top = [], []
        for v in vertices:
            if v[2] > 0:
                top.append(v)
            else:
                base.append(v)
        base_and_top_vertices.append([base, top])
    
    return base_and_top_vertices


def draw_cuboid_2(ax, origin, size, color=(0.6, 0.8, 1.0), alpha=0.3):
    """
    Draw a transparent cuboid.
    origin: (x0, y0, z0)
    size: (L, W, H)
    """
    x0, y0, z0 = origin
    L, W, H = size

    # Define vertices
    V = np.array([
        [x0,     y0,     z0],
        [x0+L,   y0,     z0],
        [x0+L,   y0+W,   z0],
        [x0,     y0+W,   z0],
        [x0,     y0,     z0+H],
        [x0+L,   y0,     z0+H],
        [x0+L,   y0+W,   z0+H],
        [x0,     y0+W,   z0+H]
    ])

    # Faces of cuboid
    F = [
        [0,1,2,3],
        [4,5,6,7],
        [0,1,5,4],
        [1,2,6,5],
        [2,3,7,6],
        [3,0,4,7]
    ]

    poly3d = [[V[vert] for vert in face] for face in F]
    ax.add_collection3d(
        Poly3DCollection(poly3d, 
                         facecolors=[color],
                         linewidths=1,
                         edgecolors='k',
                         alpha=alpha)
    )

def draw_cuboid(ax, center, size, color='cyan', alpha=0.3):

    cx, cy, cz = center
    dx, dy, dz = size

    # Half-dimensions
    hx, hy, hz = dx / 2, dy / 2, dz / 2

    # Cuboid corners
    x = [cx - hx, cx + hx]
    y = [cy - hy, cy + hy]
    z = [cz - hz, cz + hz]

    vertices = [
        [x[0], y[0], z[0]], [x[1], y[0], z[0]], [x[1], y[1], z[0]], [x[0], y[1], z[0]],
        [x[0], y[0], z[1]], [x[1], y[0], z[1]], [x[1], y[1], z[1]], [x[0], y[1], z[1]]
    ]

    faces = [
        [vertices[0], vertices[1], vertices[2], vertices[3]],
        [vertices[4], vertices[5], vertices[6], vertices[7]],
        [vertices[0], vertices[1], vertices[5], vertices[4]],
        [vertices[2], vertices[3], vertices[7], vertices[6]],
        [vertices[1], vertices[2], vertices[6], vertices[5]],
        [vertices[4], vertices[7], vertices[3], vertices[0]],
    ]

    ax.add_collection3d(
        Poly3DCollection(faces, facecolors=color, edgecolors='k', linewidths=0.3, alpha=alpha)
    )
